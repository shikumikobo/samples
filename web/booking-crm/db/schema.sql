-- 予約と顧客管理（見本）の表。docs/contract.md §3 と同じ。
-- サロン（時間で取る）と教室（クラス枠）で、表の形は同じ。データだけが違う。
create extension if not exists btree_gist;

create table settings (
  key   text primary key,
  value text not null
);

create table services (
  id              text primary key,
  name            text not null,
  kind            text not null check (kind in ('timed', 'class')),
  duration_min    int  not null check (duration_min > 0),
  price           int  not null check (price >= 0),
  is_trial        boolean not null default false,
  first_time_only boolean not null default false,
  return_days     int check (return_days is null or return_days > 0),
  image           text,
  description     text not null default '',
  sort            int  not null default 0,
  active          boolean not null default true
);

create table staff (
  id     text primary key,
  name   text not null,
  title  text not null default '',
  active boolean not null default true
);

create table staff_hours (
  staff_id   text not null references staff(id),
  weekday    int  not null check (weekday between 0 and 6),   -- 0=日…6=土
  open_time  time not null,
  close_time time not null,
  primary key (staff_id, weekday),
  check (open_time < close_time)
);

create table staff_off (
  staff_id text not null references staff(id),
  day      date not null,
  note     text not null default '',
  primary key (staff_id, day)
);

-- 教室の「くり返し」の決まり（毎週・毎月）。期限（until_day）までの日にちを、class_sessions に1回ずつ作る
create table session_series (
  id         text primary key,
  service_id text not null references services(id),
  staff_id   text not null references staff(id),
  repeat     text not null check (repeat in ('weekly', 'monthly')),  -- 毎週（同じ曜日）／毎月（同じ日付。月末を超える月は月末）
  start_day  date not null,
  until_day  date not null,
  start_time time not null,
  end_time   time not null,
  capacity   int  not null check (capacity > 0),
  check (start_day <= until_day),
  check (start_time < end_time)
);

create table class_sessions (
  id         text primary key,
  service_id text not null references services(id),
  staff_id   text not null references staff(id),
  starts_at  timestamptz not null,
  ends_at    timestamptz not null,
  capacity   int  not null check (capacity > 0),
  series_id  text references session_series(id) on delete set null,  -- null＝日にち限定の1回
  check (starts_at < ends_at)
);

create table customers (
  id         text primary key,
  name       text not null,
  kana       text not null default '',
  phone      text not null default '',
  email      text not null default '',
  note       text not null default '',    -- お店のメモ（お客さんには見せない）
  caution    text not null default '',    -- アレルギー・注意（お客さんには見せない）
  created_at timestamptz not null default now(),
  active     boolean not null default true
);

create table reservations (
  id          text primary key,
  customer_id text not null references customers(id),
  service_id  text not null references services(id),
  staff_id    text not null references staff(id),
  session_id  text references class_sessions(id),          -- クラスのときだけ
  starts_at   timestamptz not null,
  ends_at     timestamptz not null,
  price       int  not null check (price >= 0),            -- その時点の金額
  is_trial    boolean not null default false,
  status      text not null default 'booked' check (status in ('booked', 'visited', 'canceled', 'noshow')),
  note        text not null default '',                    -- お店のメモ（キャンセルの理由・来店のひとことなど。お客さんには見せない）
  created_at  timestamptz not null default now(),
  check (starts_at < ends_at),
  -- サロン：同じ担当の重なる時間は、関数の確認に加えて、ここでも拒む（二重の守り）
  constraint reservations_no_overlap
    exclude using gist (staff_id with =, tstzrange(starts_at, ends_at) with &&)
    where (session_id is null and status <> 'canceled')
);
create index reservations_customer_idx on reservations (customer_id, starts_at);
create index reservations_session_idx  on reservations (session_id);
create index reservations_starts_idx   on reservations (starts_at);

create sequence reservation_seq start 1001;

-- トリガーが書く。更新・削除はできない（triggers.sql）
create table history (
  id             bigint generated by default as identity primary key,
  at             timestamptz not null,
  actor          text not null,              -- 'shop' または 'customer:<id>'
  action         text not null,              -- create / change / cancel / visit / noshow / update
  reservation_id text not null,
  before         jsonb,
  after          jsonb
);
create index history_reservation_idx on history (reservation_id, at);
